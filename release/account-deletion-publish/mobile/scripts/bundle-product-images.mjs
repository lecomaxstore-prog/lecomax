import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

const mobile = fileURLToPath(new URL("../", import.meta.url));
const snapshot = JSON.parse(readFileSync(path.join(mobile, "src/data/catalog.snapshot.json"), "utf8"));
const urls = [...new Set(snapshot.products.flatMap((product) =>
  [product.thumbnail, ...product.images].filter((uri) => uri?.startsWith("/images/products/")),
))].sort();
const destination = path.join(mobile, "assets/product-fallbacks");
mkdirSync(destination, { recursive: true });
const entries = await Promise.all(urls.map(async (uri) => {
  const filename = createHash("sha256").update(uri).digest("hex").slice(0, 16) + ".webp";
  await sharp(path.join(mobile, "../public", decodeURI(uri)))
    .resize({ width: 1200, height: 1200, fit: "inside", withoutEnlargement: true })
    .webp({ quality: 88 }).toFile(path.join(destination, filename));
  return `  ${JSON.stringify(decodeURI(uri))}: require("../../assets/product-fallbacks/${filename}"),`;
}));
writeFileSync(path.join(mobile, "src/data/product-image-fallbacks.ts"),
  '// Generated by scripts/bundle-product-images.mjs from the original product photos.\n' +
  'export const productImageFallbacks: Record<string, number> = {\n' + entries.join('\n') + '\n};\n');
console.log(`Bundled ${urls.length} original product photos.`);
