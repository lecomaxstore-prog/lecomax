import { createServer } from 'node:http';
import { createRequire } from 'node:module';
import next from 'next';
import { labBindHost } from '../lib/teacher-lab.ts';
const require = createRequire(import.meta.url);
const config = require('../next.config.js');
const app = next({ dev: true, dir: process.cwd(), conf: { ...config, distDir: 'out/notifications-api' } });
await app.prepare();
const host = labBindHost();
createServer(app.getRequestHandler()).listen(3002, host, () => console.log(`Learning API: http://${host}:3002`));
