import type { Journey, JourneyStep, LabKind } from './journeys';

// Each pair asks learners to predict a result, then reason about its limits.
type Check = Pick<
  JourneyStep,
  'title' | 'mission' | 'question' | 'options' | 'correct' | 'feedback' | 'hint'
>;
function journey(
  id: string,
  title: string,
  lab: LabKind,
  related: string[],
  source: string,
  sourceName: string,
  simple: string,
  deep: string,
  parts: [string, string][],
  checks: Check[],
): Journey {
  return {
    id,
    title,
    related,
    steps: checks.map((check, i) => ({
      ...check,
      id: `${id}-${i + 1}`,
      lab,
      source,
      sourceName,
      simple,
      deep,
      parts: parts.map(([name, detail]) => ({ name, detail })),
      mechanism: parts.map(([name, detail]) => `${name}: ${detail}`),
    })),
  };
}
