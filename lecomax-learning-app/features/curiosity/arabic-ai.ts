export function localizeJourney(
  journey: Journey | undefined,
  language: string,
): Journey | undefined {
  if (!journey || language !== 'ar' || journey.id !== 'ai') return journey;
  return {
    ...journey,
    title: 'كيف يعمل الذكاء الاصطناعي؟',
    steps: journey.steps.map((step) => ({ ...step, ...arabicAI[step.id] })),
  };
}
